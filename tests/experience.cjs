const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await context.route('**/api/**', r => r.fulfill({ status: 503, json: { error: 'offline' } }));
  await context.route('**/.netlify/functions/**', r => r.fulfill({ json: null }));
  await context.addInitScript(() => {
    localStorage.setItem('mhs:ftue:v1', JSON.stringify({ intro: 1, tour: 1, tips: {} }));
    if (!localStorage.getItem('muhasabah:data:v1')) localStorage.setItem('muhasabah:data:v1', JSON.stringify({ onboarded: true, lang: 'en', habits: [], todos: [], ledger: [] }));
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto((process.env.BASE || 'http://localhost:8889') + '/');
  await page.locator('.mhs-rf-card').waitFor();
  assert.equal(await page.locator('mhs-feed-home .mhs-rf-card').count(), 1);
  assert.deepEqual(await page.locator('mhs-feed-home').evaluate(h => Array.from(h.children, n => n.tagName === 'MHS-PRAYER-STRIP' ? 'prayer' : n.className)), ['prayer', 'mhs-home-feed', 'panel mhs-home-summary', 'panel mhs-home-apps']);
  assert.equal(await page.locator('mhs-prayer-strip').count(), 1);
  assert.equal(await page.locator('.mhs-story-progress span').count(), 5);
  assert.equal(await page.locator('.mhs-rf-card .mhs-story-actions button').count(), 5);
  const height = await page.locator('.mhs-rf-card').evaluate(n=>n.offsetHeight);
  await page.locator('.mhs-story-next').click();
  assert.equal(await page.locator('.mhs-rf-card').evaluate(n=>n.offsetHeight),height);
  await page.locator('.mhs-fab').click();
  assert(await page.locator('.mhs-fab-menu').evaluate(n=>n.getBoundingClientRect().width<=64));
  assert.equal(await page.locator('.mhs-fab-item .lbl').first().isVisible(),false);
  await page.locator('.mhs-fab').click();
  assert.equal(await page.evaluate(() => ['backup','drive','csv','analytics','media'].every(k => MHSGate.has(k))), true);
  assert.equal(await page.locator('.mhs-home-stats b').count(), 3);
  const appKeys = await page.locator('.mhs-home-app').evaluateAll(nodes => nodes.map(n => n.dataset.app));
  assert.deepEqual(appKeys.slice().sort(), await page.evaluate(() => MHSActions.items().map(i => i.key).sort()));
  assert(appKeys.includes('seerah'));
  await page.locator('.mhs-home-summary-link').click();
  await page.locator('mhs-overview').waitFor();
  assert.equal(await page.locator('mhs-feed-home').count(), 0);
  await page.evaluate(() => MHSApp.nav('home'));
  await page.locator('mhs-feed-home .mhs-rf-card').waitFor();
  await page.locator('.mhs-home-app[data-app="quran"]').click();
  await page.locator('#mhs-quran').waitFor();
  await page.evaluate(() => document.querySelector('#mhs-quran').close());
  await page.waitForTimeout(500);
  for (const width of [320, 768, 1280]) {
    await page.setViewportSize({ width, height: 844 });
    assert(await page.locator('mhs-feed-home').evaluate(h => h.scrollWidth <= h.clientWidth + 1));
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Feed settings', exact: true }).click();
  assert.equal(await page.locator('.mhs-feed-sources input').count(), 5);
  assert.equal(await page.locator('.mhs-feed-sources input').last().isChecked(), false);
  await page.locator('.mhs-feed-sources input').first().uncheck();
  assert.equal(await page.evaluate(() => MHSX.get('feedSources').verse), false);
  await page.evaluate(() => MHSQuran.open());
  const toolbarCount = await page.locator('#mhs-quran .mhs-mini-tools > *').count();
  await page.locator('#mhs-quran [data-reader-settings]').click();
  assert.equal(await page.locator('#mhs-quran .mhs-mini-tools > *').count(), toolbarCount);
  assert.equal(await page.locator('#mhs-reader-settings [data-reader-settings]').count(), 0);
  const size = page.locator('#mhs-reader-settings input[type=range]');
  await size.fill('28'); await size.dispatchEvent('input');
  assert.equal(await page.evaluate(() => MHSX.get('reader:mhs-quran').size), 28);
  assert.equal(await page.locator('#mhs-reader-settings output').textContent(), '28 px');
  await page.getByLabel('Arabic font', { exact: true }).selectOption('Noto Naskh Arabic');
  assert.equal(await page.locator('#mhs-quran .mhs-mini-body').evaluate(n => n.style.getPropertyValue('--mhs-arabic')), 'Noto Naskh Arabic, serif');
  await page.getByLabel('Continuous Mushaf layout', { exact: true }).check();
  assert(await page.locator('#mhs-quran').evaluate(n => n.classList.contains('mhs-mushaf')));
  await page.evaluate(() => document.querySelectorAll('dialog[open]').forEach(d => d.close()));
  await page.waitForTimeout(500);
  await page.evaluate(() => MHSCollections.choose({ id: 'j:2026-11-16', kind: 'journal', day: '2026-11-16', title: 'A saved day' }));
  await page.locator('#mhs-collection-picker input').fill('Reflections');
  await page.locator('#mhs-collection-picker').getByRole('button', { name: 'Save', exact: true }).click();
  assert.equal(await page.evaluate(() => MHSBookmarks.collect().find(r => r.id === 'j:2026-11-16').collection), 'Reflections');
  await page.evaluate(() => MHSQuickTodo());
  await page.locator('#mhs-quick-todo input').fill('Read after Fajr');
  await page.locator('#mhs-quick-todo button[type=submit]').click();
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => MHSApp.todos()[0].title), 'Read after Fajr');
  assert.equal(await page.evaluate(() => MHSApp.todos()[0].date), await page.evaluate(() => MHS.dayKey()));
  await page.evaluate(() => MHSApp.newTodo());
  await page.locator('#mhs-tw-date').waitFor();
  await page.locator('#mhs-tw-date').fill('2026-12-01');
  assert.equal(await page.locator('#mhs-tw-date').inputValue(), '2026-12-01');
  assert.equal(await page.evaluate(() => MHSShareConfig.url), 'https://muhasabah-pro.netlify.app/');
  assert.deepEqual(errors, []);
  await page.route('https://api.alquran.cloud/**', r => r.fulfill({json:{data:[{ayahs:[{numberInSurah:1,text:'بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ'}]},{ayahs:[{text:'In the name of Allah, the Entirely Merciful, the Especially Merciful.'}]}]}}));
  await page.evaluate(() => MHSQuran.download(1));
  await context.setOffline(true);
  await page.evaluate(() => document.querySelectorAll('dialog[open]').forEach(d => d.close()));
  await page.waitForTimeout(500);
  await page.evaluate(() => MHSQuran.open({surah:1}));
  await page.locator('#mhs-quran .mhs-q-ayah').waitFor();
  assert.equal(await page.locator('#mhs-quran .mhs-q-ayah').count(), 1);
  await browser.close();
  console.log('Experience: feed sources, reader preferences, bookmark collections, quick tasks, dates, share URL and downloaded Quran offline passed');
})().catch(e => { console.error(e); process.exit(1); });
