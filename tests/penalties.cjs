const assert = require('node:assert/strict');
require('../pwa/penalties.js');
const date = (day,hour=0) => new Date(2026,9,day,hour);
const habit = {id:'test',title:'Reading',points:10,status:'active',repeat:['Everyday'],createdAt:date(1).getTime()};
const deadline = (_, day) => new Date(day.getFullYear(),day.getMonth(),day.getDate(),10).getTime();
const run = (habits=[habit],ledger=[],now=date(31,11),since=date(1).getTime(),dl=deadline) => MHSPenalties.reconcile(habits,ledger,now,since,dl);
const all=run();
assert.equal(all.length,31,'catch up beyond the former 14-day limit');
assert.equal(all.reduce((s,e)=>s+e.delta,0),-310);
assert.equal(run([habit],all).length,0,'reopening never charges twice');
assert.equal(run([habit],[{type:'checkIn',habitId:'test',ts:date(2,9).getTime()}]).length,30);
assert.equal(run([habit],[{type:'excuse',ts:date(3,9).getTime()}]).length,30);
assert.equal(run([{...habit,status:'paused'}]).length,0);
assert.equal(run([{...habit,autoPenalty:false}]).length,0);
assert.equal(run([{...habit,createdAt:date(31,11).getTime()}]).length,0,'no penalties before creation');
assert.equal(run([{...habit,repeat:['Mon']}]).length,4,'only scheduled weekdays');
assert.equal(run([habit],[],date(1,9)).length,0,'before deadline');
assert.equal(run([habit],[],date(1,10),date(1).getTime(),(_,d)=>deadline(_,d)+600000).length,0,'honor grace time');
const overnight=run([habit],[],date(2,1),date(1).getTime(),(_,d)=>new Date(d.getFullYear(),d.getMonth(),d.getDate()+1).getTime());
assert.equal(overnight.length,1);
assert.equal(run([habit],overnight,date(2,1),date(1).getTime(),(_,d)=>new Date(d.getFullYear(),d.getMonth(),d.getDate()+1).getTime()).length,0,'grace crossing midnight is idempotent');
console.log('Penalty reconciliation: 12 checks passed');
